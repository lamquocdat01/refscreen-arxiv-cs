#!/usr/bin/env python3
"""Topic 43 / P2 / T10e: final figures F1-F6 (PDF + PNG) from the result files; each figure gets a sidecar
figures/<F>.sources.txt with the sha256 of every source file it reads (C8b). No number is typed by hand.

F1  four verdicts on one bibliography: u_A by cumulative backend x period, paper-bootstrap 95 % CI
F2  discrete ROC per backend: FP on legitimate academic refs (u_A, 2019-21) vs recall on fabricated items (def 1 and
    def 2), per item family; main version after the recall-drop audit (results/p2_recall_audited.csv), F2b with
    the original labels (appendix)
F3  PPV ceiling vs web share w_W, two backend sets (Crossref-only, full cascade), pi = 0.39 % and 0.5 %
F4  P(false flag, k = 2) vs n for the measured tier mix of cs.CV / cs.NI / cs.CL (full cascade) + observed tertiles
F5  FP by style x variant (GROBID, union screen): certified-real vs the 58 manually verified render refs
F6  u_s by tier x period (full cascade), paper-bootstrap 95 % CI
Palette: reference categorical slots 1-3 (#2a78d6, #eb6834, #1baf7a; validated, light surface); every series is
also direct-labelled or marker-coded (slot 3 is < 3:1 against white).
Usage: python p2_figures.py --seed 42
"""
import argparse
import hashlib
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

sys.path.insert(0, str(Path(__file__).resolve().parent))
from ground_truth import ROOT  # noqa: E402

RES, FIG = ROOT / "results", ROOT / "figures"
C1, C2, C3 = "#2a78d6", "#eb6834", "#1baf7a"
INK, MUTED, GRID = "#1f1f1e", "#6b6a64", "#e4e3de"
COLS = [("crossref", "Crossref-only"), ("arxiv", "+arXiv"), ("dblp", "+DBLP"), ("openalex", "+OpenAlex"),
        ("s2", "+S2 (full)")]
plt.rcParams.update({"font.size": 9, "axes.edgecolor": MUTED, "axes.labelcolor": INK, "xtick.color": MUTED,
                     "ytick.color": MUTED, "axes.spines.top": False, "axes.spines.right": False,
                     "axes.grid": True, "grid.color": GRID, "grid.linewidth": 0.6, "axes.axisbelow": True,
                     "legend.frameon": False, "pdf.fonttype": 42})


def sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def save(fig, name, sources, seed):
    FIG.mkdir(exist_ok=True)
    for ext in ("pdf", "png"):
        fig.savefig(FIG / f"{name}.{ext}", dpi=300 if ext == "png" else None, bbox_inches="tight",
                    metadata={"Subject": f"topic 43 {name}, seed {seed}"} if ext == "pdf" else None)
    plt.close(fig)
    lines = [f"{name} (seed {seed}) generated by code/p2_figures.py from:"]
    lines += [f"{sha(RES / s)}  results/{s}" for s in sources]
    (FIG / f"{name}.sources.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote", name)


def bt_rows():
    # P3: the main table of the article is the P2 table after the night retry (2019-21 identical to P1)
    b = pd.read_csv(RES / "p2_backend_table_retry.csv", dtype=str, keep_default_na=False)
    return b


def ci(s):
    lo, hi = (float(x) for x in s.split("-"))
    return lo, hi


def f1(seed):
    b = bt_rows()
    fig, ax = plt.subplots(figsize=(6.2, 3.0))
    x = np.arange(len(COLS))
    for j, (per, col, mk) in enumerate([("2019-21", C1, "o"), ("2024-26", C2, "s")]):
        r = b[(b.period == per) & (b.stratum == "A")].iloc[0]
        u = np.array([float(r[f"u_{c}"]) for c, _ in COLS]) * 100
        lohi = np.array([ci(r[f"boot_{c}"]) for c, _ in COLS]) * 100
        xx = x + (j - 0.5) * 0.36
        ax.bar(xx, u, width=0.32, color=col, label=f"{per} (n = {int(r.n):,} refs, {int(r.n_papers)} papers)",
               edgecolor="white", linewidth=1.0)
        ax.errorbar(xx, u, yerr=[u - lohi[:, 0], lohi[:, 1] - u], fmt="none", ecolor=INK, elinewidth=0.8, capsize=2)
        for xi, top, ui in zip(xx, lohi[:, 1], u):
            ax.text(xi, top + 0.6, f"{ui:.1f}", ha="center", va="bottom", fontsize=7, color=INK)
    ax.set_xticks(x, [lab for _, lab in COLS])
    ax.set_ylabel("Unresolved legitimate academic refs, u_A (%)")
    ax.set_ylim(0, 40)
    ax.legend(loc="upper right", fontsize=8)
    ax.set_title("Same references, five backend sets: u_A by cumulative backend set (def 1, 95 % paper-bootstrap CI)",
                 fontsize=9, loc="left", color=INK)
    save(fig, "F1_four_verdicts", ["p2_backend_table_retry.csv"], seed)


def f2(seed, audited=True):
    """audited=True (main): GPTZero / Badalova-Mayr recall after the recall-drop audit (LABEL_WRONG removed,
    results/p2_recall_audited.csv); audited=False: original labels (appendix)."""
    p = RES / "p2_recall.csv"
    if not p.exists():
        print("F2 skipped: results/p2_recall.csv missing")
        return
    rc = pd.read_csv(p)
    pa = RES / "p2_recall_audited.csv"
    if audited:
        if not pa.exists():
            print("F2 (audited) skipped: results/p2_recall_audited.csv missing")
            return
        ra = pd.read_csv(pa)
        ra = ra[ra.version.str.startswith("after audit")].drop(columns="version")
        rc = pd.concat([rc[~rc["set"].isin(ra["set"].unique())], ra], ignore_index=True)
    b = bt_rows()
    r = b[(b.period == "2019-21") & (b.stratum == "A")].iloc[0]
    keys = ["crossref" if c == "crossref" else f"+{c}" for c, _ in COLS]
    fp = {k: float(r[f"u_{c}"]) * 100 for k, (c, _) in zip(keys, COLS)}
    fams = [("gen_a", "fabricated", "fabricated title (gen; 100 % by construction)", C1, "o"),
            ("gptzero", "hallucinated", "GPTZero NeurIPS 2025 (n = 99 after audit)" if audited else
             "GPTZero NeurIPS 2025 (n = 100, original labels)", C2, "s"),
            ("gen_b", "fabricated", "real title, swapped authors (gen, n = 100)", C3, "^")]
    # P3: one panel only. The horizontal axis is the def-1 false-positive rate, so only def-1 recall is paired with
    # it (the def-2 panel of P2 plotted def-2 recall against the def-1 FP); def-2 recall is in Table 6 of the article.
    # R2 Q18: readable at print width (the figure is set at \linewidth, about 5.3 in): no text below 7.5 pt, backend
    # names on a top axis instead of rotated point labels, the explanatory note moved to the caption
    fig, ax0 = plt.subplots(1, 1, figsize=(5.4, 4.0))
    fig.subplots_adjust(bottom=0.30, top=0.84, left=0.12, right=0.97)
    axes = [ax0]
    for ax, d in zip(axes, (1,)):
        for st, lab, name, col, mk in fams:
            g = rc[(rc["set"] == st) & (rc.label == lab) & (rc.definition == d)].set_index("screen").loc[keys]
            xs = [fp[k] for k in keys]
            ys = g.share_flagged.values * 100
            ax.plot(xs, ys, color=col, marker=mk, markersize=6, linewidth=1.6, label=name)
            lo, hi = g.bound_lo.values * 100, g.bound_hi.values * 100
            ax.errorbar(xs, ys, yerr=[np.clip(ys - lo, 0, None), np.clip(hi - ys, 0, None)], fmt="none", ecolor=col,
                        elinewidth=0.9, capsize=2.5)
        ax.set_xscale("log")  # before the secondary axis: setting the scale afterwards resets its ticks
        ax.set_xticks([2, 3, 5, 10, 20, 30], ["2", "3", "5", "10", "20", "30"], fontsize=8.5)
        ax.minorticks_off()
        top = ax.secondary_xaxis("top")
        tk = [(fp[k], {"crossref": "Crossref", "+arxiv": "+arXiv", "+dblp": "+DBLP\n+OpenAlex", "+s2": "+S2"}[k])
              for k in keys if k != "+openalex"]  # +OpenAlex sits 0.4 points left of +DBLP: labelled together
        top.set_xticks([t for t, _ in tk], [s for _, s in tk], fontsize=8, color=INK)
        top.xaxis.set_minor_locator(matplotlib.ticker.NullLocator())
        top.tick_params(length=3)
        ax.tick_params(axis="y", labelsize=8.5)
        ax.set_xlabel("False-positive rate: unresolved legitimate academic refs, 2019-21 (%, log scale)",
                      fontsize=8.5)
        ax.set_ylim(-3, 103)
    axes[0].set_ylabel("Recall on fabricated items (%)", fontsize=8.5)
    fig.legend(*axes[0].get_legend_handles_labels(), loc="lower center", ncol=1, fontsize=8,
               bbox_to_anchor=(0.55, 0.0))
    if audited:
        save(fig, "F2_roc_backend", ["p2_recall.csv", "p2_recall_audited.csv", "p2_recall_drop_audit.csv",
                                     "p2_backend_table_retry.csv"], seed)
    else:
        save(fig, "F2b_roc_backend_original_labels", ["p2_recall.csv", "p2_backend_table_retry.csv"], seed)


def f3(seed):
    t = pd.read_csv(RES / "p1_theory_tables.csv", dtype=str, keep_default_na=False)
    t = t[t.table == "ppv_vs_wW"]
    fig, ax = plt.subplots(figsize=(5.2, 3.0))
    for sc, name, col, mk in [("full", "full cascade (+S2)", C1, "o"), ("crossref_only", "Crossref-only", C2, "s")]:
        for pn, ls in [("0.39%", "-"), ("0.5%", "--")]:
            g = t[(t.scenario == sc) & t.pi_name.str.endswith(pn)].astype({"w_W": float, "ppv_ceiling": float})
            g = g.sort_values("w_W")
            ax.plot(g.w_W * 100, g.ppv_ceiling * 100, color=col, linestyle=ls, linewidth=1.6,
                    label=f"{name}, pi = {pn}")
    ax.set_yscale("log")
    ax.set_xlabel("Share of web references in the bibliography, w_W (%)")
    ax.set_ylabel("PPV ceiling (%, log)")
    ax.legend(fontsize=7, loc="upper right")
    ax.set_title("Prop. 1: ceiling on the share of flags that are fabrications", fontsize=9, loc="left")
    save(fig, "F3_ppv_ceiling", ["p1_theory_tables.csv"], seed)


def f4(seed):
    t = pd.read_csv(RES / "p1_theory_tables.csv", dtype=str, keep_default_na=False)
    t = t[(t.table == "pff_vs_n") & (t.scenario == "full") & (t.k == "2.0")].astype({"n": float, "exact": float})
    h = pd.read_csv(RES / "p1_h5.csv")
    h = h[h.scenario == "full"]
    fig, ax = plt.subplots(figsize=(5.2, 3.1))
    for f, col, mk in [("cs.CV", C1, "o"), ("cs.NI", C2, "s"), ("cs.CL", C3, "^")]:
        g = t[t.field == f].sort_values("n")
        ax.plot(g.n, g.exact * 100, color=col, marker=mk, markersize=4, linewidth=1.6, label=f"Prop. 2(a), {f} mix")
    ax.errorbar(h.n_refs_median, h.obs * 100, yerr=[(h.obs - h.wilson_lo) * 100, (h.wilson_hi - h.obs) * 100],
                fmt="D", color=INK, markersize=5, capsize=2, label="observed, all fields (tertiles, Wilson)")
    ax.set_xlim(0, 160)
    ax.set_xlabel("Bibliography length n (curves reach 100 % beyond n = 160)")
    ax.set_ylabel("P(legitimate paper flagged, k = 2) (%)")
    ax.set_ylim(0, 105)
    ax.legend(fontsize=7, loc="lower right")
    ax.set_title("Prop. 2(a) (independence) over-predicts flags on long papers (H5 FAIL)", fontsize=9, loc="left")
    save(fig, "F4_pff_vs_n", ["p1_theory_tables.csv", "p1_h5.csv"], seed)


def f5(seed):
    m = pd.read_csv(RES / "p2_render_manual_fp.csv")
    m = m[(m.parser == "grobid") & (m.screen == "union")]
    lab = [f"{s}\n{v}" for s, v in zip(m["style"], m.variant)]
    x = np.arange(len(m))
    fig, ax = plt.subplots(figsize=(6.2, 3.0))
    ax.bar(x - 0.18, m.fp_cert * 100, width=0.34, color=C1, edgecolor="white",
           label=f"certified-real (n ~ {int(m.n_cert.median()):,} refs, 97 papers)")
    ax.bar(x + 0.18, m.fp_manual * 100, width=0.34, color=C2, edgecolor="white",
           label=f"AI-agent-verified, no identifier (n = {int(m.n_manual.min())}-{int(m.n_manual.max())} refs)")
    ax.errorbar(x + 0.18, m.fp_manual * 100, yerr=[(m.fp_manual - m.wilson_lo) * 100, (m.wilson_hi - m.fp_manual) * 100],
                fmt="none", ecolor=INK, elinewidth=0.8, capsize=2)
    for xi, a, top, bb in zip(x, m.fp_cert * 100, m.wilson_hi * 100, m.fp_manual * 100):
        ax.text(xi - 0.18, a + 0.8, f"{a:.2f}", ha="center", fontsize=6, color=INK)
        ax.text(xi + 0.18, top + 0.8, f"{bb:.0f}", ha="center", fontsize=6, color=INK)
    ax.set_xticks(x, lab, fontsize=7)
    ax.set_ylabel("FP of the full-cascade screen (%)")
    ax.legend(fontsize=7, loc="upper center", ncol=2, bbox_to_anchor=(0.5, 1.0))
    ax.set_ylim(0, 52)
    ax.set_title("FP by style: certified-real vs AI-agent-verified render refs (GROBID, union)", fontsize=9, loc="left")
    save(fig, "F5_fp_style", ["p2_render_manual_fp.csv"], seed)


def f6(seed):
    b = bt_rows()
    tiers = ["J", "C", "P", "B", "S", "W"]
    fig, ax = plt.subplots(figsize=(5.6, 3.0))
    x = np.arange(len(tiers))
    for j, (per, col) in enumerate([("2019-21", C1), ("2024-26", C2)]):
        g = b[(b.period == per)].set_index("stratum").loc[tiers]
        u = g.u_s2.astype(float).values * 100
        lohi = np.array([ci(s) for s in g.boot_s2]) * 100
        xx = x + (j - 0.5) * 0.36
        ax.bar(xx, u, width=0.32, color=col, edgecolor="white", label=per)
        ax.errorbar(xx, u, yerr=[u - lohi[:, 0], lohi[:, 1] - u], fmt="none", ecolor=INK, elinewidth=0.8, capsize=2)
        for xi, top, ui in zip(xx, lohi[:, 1], u):
            ax.text(xi, top + 1.0, f"{ui:.1f}", ha="center", va="bottom", fontsize=6, color=INK)
    ax.set_xticks(x, ["journal", "conference", "preprint", "book", "software", "web"])
    ax.set_ylabel("u_s, full cascade (%)")
    ax.set_ylim(0, 110)
    ax.legend(fontsize=8, loc="upper left")
    ax.set_title("Unresolved rate of legitimate refs by tier and period (def 1, 95 % CI)", fontsize=9, loc="left")
    save(fig, "F6_u_by_tier", ["p2_backend_table_retry.csv"], seed)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=int, default=42)
    args = ap.parse_args()
    for f in (f1, f2, f3, f4, f5, f6):
        f(args.seed)
    f2(args.seed, audited=False)


if __name__ == "__main__":
    main()
