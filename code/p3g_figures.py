#!/usr/bin/env python3
"""Topic 43 / P3G: re-draw F1 and F5 with corrected wording (S6' S3, mismatch row 12: "five backend sets",
"AI-agent-verified"), from the same result files as the _p3e figures, without touching any earlier figure.
F1 reads results/p2_backend_table_retry_p3e.csv, F5 results/p2_render_manual_fp.csv (the files the _p3e figures used).
Writes figures/F1_four_verdicts_p3g.{pdf,png,sources.txt} and figures/F5_fp_style_p3g.{pdf,png,sources.txt}.
Usage: python code/p3g_figures.py --seed 42
"""
import argparse
import shutil
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import p2_figures as pf  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=int, default=42)
    args = ap.parse_args()
    with tempfile.TemporaryDirectory() as td:
        td = Path(td)
        res, fig = td / "results", td / "figures"
        res.mkdir()
        shutil.copyfile(ROOT / "results" / "p2_backend_table_retry_p3e.csv", res / "p2_backend_table_retry.csv")
        shutil.copyfile(ROOT / "results" / "p2_render_manual_fp.csv", res / "p2_render_manual_fp.csv")
        pf.RES, pf.FIG = res, fig
        pf.f1(args.seed)
        pf.f5(args.seed)
        for name, srcs in (("F1_four_verdicts", ["p2_backend_table_retry_p3e.csv"]), ("F5_fp_style", ["p2_render_manual_fp.csv"])):
            for ext in ("pdf", "png"):
                shutil.copyfile(fig / f"{name}.{ext}", ROOT / "figures" / f"{name}_p3g.{ext}")
            lines = [f"{name}_p3g (seed {args.seed}) generated by code/p3g_figures.py (p2_figures.f1/f5) from:"]
            lines += [f"{pf.sha(ROOT / 'results' / s)}  results/{s}" for s in srcs]
            (ROOT / "figures" / f"{name}_p3g.sources.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
